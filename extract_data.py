def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--model",
        type=str,
        default='olmo2',
        help="model to extract data from;",
    )
    parser.add_argument(
        "--num_responses",
        type=int,
        default=512,
        help="The number of responses to generate per domain;",
    )
    parser.add_argument(
        "--save_dir",
        type=str,
        default='./extraction_results',
        help="Directory to save results;",
    )
    parser.add_argument(
        "--generation_role",
        type=str,
        default='assistant',
        help="query generated by which role;",
    )

    args = parser.parse_args()
    #support predefined model or any model
    model_id = model_mappings.get(args.model, args.model) 
    print(f"Using model: {model_id}")

    #show example prompt and jailbreak
    # message = "I am content"
    # prompt = tokenizer.apply_chat_template([
    #     {"role": "user", "content": message}
    #     ], 
    #     tokenize=False, 
    #     add_generation_prompt=True
    # )
    # print(f"Prompt: {prompt}")

    if args.generation_role == 'user':
        output_file = f"querys_{args.model}_{args.num_responses}_user.csv"
    else:
        output_file = f"querys_{args.model}_{args.num_responses}.csv"
    os.makedirs(args.save_dir, exist_ok=True)
    output_file = os.path.join(args.save_dir, output_file)

    llm = LLM(model=model_id, gpu_memory_utilization=0.9)
    tokenizer = AutoTokenizer.from_pretrained(model_id)

    if not os.path.exists(output_file):
        # 1. Prepare Prompts and Metadata together
        prompts = []
        prompt_metadata = []
        
        for domain in tqdm(safety_domains, desc="Preparing prompts"):
            jailbreak = generate_jailbreak(tokenizer, domain, args.model, args.generation_role)
            prompts.append(jailbreak)
            prompt_metadata.append({'domain': domain, 'jailbreak': jailbreak})

        extraction_params = SamplingParams(
            temperature=1.0, 
            max_tokens=256, 
            n=args.num_responses
        )

        # 2. Batch Generation
        outputs = llm.generate(prompts, extraction_params)

        # 3. Consolidate Processing
        results = []
        
        # zip() allows us to iterate over metadata and outputs simultaneously
        for meta, request_output in zip(prompt_metadata, outputs):
            for completion in request_output.outputs:
                response_text = completion.text
                
                # Simplified parsing logic
                quote_index = response_text.find('"')
                query = response_text[:quote_index] if quote_index != -1 else "None"

                # Create a single dictionary for this row
                results.append({
                    'domain': meta['domain'],
                    'jailbreak': meta['jailbreak'],
                    'original_text': response_text,
                    'query': query
                })

        # 4. Create DataFrame and Save
        df = pd.DataFrame(results)
        df.to_csv(output_file, index=False)
        print(f"Saved extracted queries to {output_file}")
    else:
        print(f"Output file {output_file} already exists. Skipping query extraction.")
        df = pd.read_csv(output_file)

    df = df[df['query'] != "None"].reset_index(drop=True)
    query_list = df['query'].tolist()

    for i, row in df.iterrows():
        print(f"Example {i}\n")
        print(f"Domain: \n{row['domain']}")
        print(f"Jailbreak Prompt: \n{row['jailbreak']}")
        print(f"Original Text: \n{row['original_text']}")
        print(f"Extracted Query: \n{row['query']}")
        print("End of Example\n")
        if i>=50:
            break

    print(f"Generating model responses for {len(query_list)} queries...")
    prompts = [
        tokenizer.apply_chat_template([{"role": "user", "content": query}], tokenize=False, add_generation_prompt=True)
        for query in query_list
    ]

    sampling_params = SamplingParams(temperature=0.8, max_tokens=1024, top_p=0.95)

    outputs = llm.generate(prompts, sampling_params, use_tqdm=False)

    model_responses = []
    print("Generating model responses...")
    for i, output in enumerate(outputs):
        generated_text = output.outputs[0].text
        model_responses.append(generated_text)

    df['response'] = model_responses
    df = df.dropna(subset=['query', 'response']).reset_index(drop=True)

    df['query'] = df['query'].astype(str)
    df['response'] = df['response'].astype(str)

    if args.generation_role == 'user':
        output_file = f"qa_{args.model}_{args.num_responses}_user.csv"
    else:
        output_file = f"qa_{args.model}_{args.num_responses}.csv"
    
    output_file = os.path.join(args.save_dir, output_file)
    df.to_csv(output_file, index=False)
    print(f"Saved model QA to {output_file}")

if __name__ == "__main__":
    main()
    if dist.is_initialized():
        dist.destroy_process_group()